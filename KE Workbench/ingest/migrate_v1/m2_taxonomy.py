"""Step 2: taxonomies. Core job taxonomy, persona and product clean-up, hyphen-joined concept IRIs (decision 5),
and every concept relinked to its primitives: dcterms:subject to each, core:hasPrimaryTerm to the head (decision 4)."""
import csv, datetime, pathlib, re, sys, collections
import kb
from kb import I, L, SK, RDF, RDFS, OWL, DCT, XSD, TYPE, CORE, BASE

SRC, VOC, OUT = (pathlib.Path(x) for x in sys.argv[1:4])     # in/ (taxonomies), m1/ (vocabularies), out
NOW = L(datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'), None, XSD + 'dateTime')
TODAY = L('2026-10-19', None, XSD + 'date')
AUTHOR = L('Jeffrey Wallk')
PRIMARY, FB = CORE + 'hasPrimaryTerm', CORE + 'formalizedBy'
(OUT / 'ttl').mkdir(parents=True, exist_ok=True); (OUT / 'trig').mkdir(parents=True, exist_ok=True)

T = {p.name[:-10]: kb.Asset(p) for p in sorted((SRC / 'ttl').glob('taxonomy-core-*-0.1.0.ttl'))}
V = {p.name[:-10]: kb.Asset(p) for p in sorted((VOC / 'ttl').glob('vocabulary-core-*-0.1.0.ttl'))}
cross, report = [], collections.defaultdict(list)

def gov(a, s, created=TODAY):
    a.set(s, CORE + 'hasLifecycleStatus', [I(CORE + 'Draft')]); a.set(s, OWL + 'versionInfo', [L('0.1.0')])
    a.set(s, DCT + 'creator', [AUTHOR])
    if not a.objs(s, DCT + 'created'): a.set(s, DCT + 'created', [created])
    a.set(s, DCT + 'modified', [NOW])

# ── 1. persona: no role typing; product: marketing stages out ─────────────────
per = T['taxonomy-core-persona']
gone = [s[1] for s in per.concepts() if s[1].endswith(('EngineeringPersona', '/PersonaRole'))]
per.remove(gone); cross += [(x, '', 'removed: personas are not typed by role (decision 23)') for x in gone]
prod = T['taxonomy-core-product']
gone = [prod.iri + x for x in ('Introduction', 'Growth', 'Maturity', 'Decline')]
prod.remove(gone); cross += [(x, '', 'removed: products use the asset lifecycle stages (decisions 11, 24)') for x in gone]

# ── 2. core job taxonomy ─────────────────────────────────────────────────────
tpl = T['taxonomy-core-requirements']
jt = kb.Asset.__new__(kb.Asset)
jt.path = SRC / 'ttl' / 'taxonomy-core-job-0.1.0.ttl'
iri = BASE + 'taxonomy/core-job/'
jt.head = ('# Core job taxonomy\n# ' + iri + '  ·  version 0.1.0  ·  Draft\n# Generated by migrate_v1.py on ' + NOW[1] + ' from design-decisions.md (Jobs model)\n'
           '# Standards: Semantic Governance: Services, Architecture & Integration v1.9 (Draft), Part III\n')
jt.prefixes = dict(tpl.prefixes); jt.prefixes['jobtax'] = iri; jt.prefixes['jobvoc'] = BASE + 'vocabulary/core-job/'
jt.g, jt.order = collections.OrderedDict(), []
h = I(iri); jt.header, jt.iri = h, iri
hp = tpl.g[tpl.header]
jt.set(h, TYPE, [I(SK + 'ConceptScheme')])
for p in (RDFS + 'label', SK + 'prefLabel', DCT + 'title'): jt.set(h, p, [L('Core job taxonomy', 'en')])
jt.set(h, DCT + 'description', [L('A taxonomy of the Jobs model (Jobs To Be Done) that supports the persona model: jobs by kind, the steps within a job, the desired and delivered outcomes mapped to each step, and the parties and studies around them. Job steps are akin to process steps but intentionally not one-to-one.', 'en')])
for p in (DCT + 'subject', DCT + 'publisher', DCT + 'conformsTo', DCT + 'language'): jt.set(h, p, hp.get(p, []))
jt.set(h, 'http://www.linkedmodel.org/schema/vaem#namespace', [L(iri, None, XSD + 'anyURI')])
jt.set(h, 'http://purl.org/vocab/vann/preferredNamespacePrefix', [L('jobtax')])
jt.set(h, DCT + 'source', [I(BASE + 'vocabulary/core-job/')])
jt.set(h, SK + 'changeNote', [L('0.1.0 (2026-10-19): created for Baseline Core v1.0 from the Jobs model (decisions 16-21).', 'en')])
jt.set(h, OWL + 'versionIRI', [I(iri + '0.1.0/')]); gov(jt, h); jt.set(h, DCT + 'contributor', [AUTHOR])
JOB = [  # label, broader label, definition, formalized by (core class local name)
 ('Job', None, 'An activity that a party is trying to get done, described independently of any product, service or process that might help.', 'job'),
 ('Functional job', 'Job', 'A job concerned with the practical task the party is trying to get done.', None),
 ('Emotional job', 'Job', 'A job concerned with how the party wants to feel, or to be perceived, while getting a task done.', None),
 ('Core job', 'Job', 'A job that a persona is principally trying to get done.', None),
 ('Related job', 'Job', 'A job that accompanies a core job, such as controlling its cost or managing its risk.', None),
 ('Job step', None, 'A step that a job executor takes within a job. Job steps are unique to the job and are not the selling steps of a provider.', 'job-step'),
 ('Desired outcome', None, 'An outcome a job executor wants at a job step, stated as a direction (minimize or maximize), a metric and a target.', 'desired-outcome'),
 ('Delivered outcome', None, 'An outcome that a product, service or process step actually achieves at a job step.', 'delivered-outcome'),
 ('Job executor', None, 'A party that performs a job.', 'role'),
 ('Job study', None, 'A study of the jobs, job steps and desired outcomes of a persona within a defined scope.', 'information-asset'),
]
byl = {}
for lab, br, d, fb in JOB:
    s = I(iri + kb.slug(lab)); byl[lab] = s
    jt.set(s, TYPE, [I(SK + 'Concept')]); jt.set(s, RDFS + 'label', [L(lab, 'en')]); jt.set(s, SK + 'prefLabel', [L(lab, 'en')])
    jt.set(s, SK + 'definition', [L(d, 'en')]); jt.set(s, SK + 'inScheme', [h])
    if br: jt.set(s, SK + 'broader', [byl[br]]); jt.add(byl[br], SK + 'narrower', s)
    else: jt.set(s, SK + 'topConceptOf', [h]); jt.add(h, SK + 'hasTopConcept', s)
    if fb: jt.set(s, FB, [I(CORE + fb)])
    gov(jt, s)
T['taxonomy-core-job'] = jt

# ── 3. hyphen-joined IRIs ────────────────────────────────────────────────────
ren = {}
for n, a in T.items():
    used = set()
    for s in a.concepts():
        local = s[1][len(a.iri):]
        new = kb.slug(a.pref(s) or local)
        base, i = new, 2
        while new in used: new = f'{base}-{i}'; i += 1
        used.add(new)
        if new != local: ren[s[1]] = a.iri + new
for a in T.values(): a.rename(ren)
cross += [(o, nw, 'concept IRI joins its primitives with hyphens (decision 5)') for o, nw in ren.items()]

# ── 3b. broader/narrower must stay inside the scheme ─────────────────────────
for n, a in T.items():
    mine = set(a.concepts())
    for s in a.concepts():
        for p in (SK + 'broader', SK + 'narrower'):
            bad = [o for o in a.objs(s, p) if o not in mine]
            if bad:
                a.set(s, p, [o for o in a.objs(s, p) if o in mine])
                report['outside'].append(f'{s[1]} {p.split("#")[1]} {", ".join(o[1] for o in bad)} (not in the scheme) removed')
        if not a.objs(s, SK + 'broader') and not a.objs(s, SK + 'topConceptOf'):
            a.set(s, SK + 'topConceptOf', [a.header]); a.add(a.header, SK + 'hasTopConcept', s)
            report['outside'].append(f'{s[1]} is now a top concept')

# ── 4. relink to primitives ──────────────────────────────────────────────────
idx = {}
for n, a in V.items():
    for s in a.concepts():
        for p in (SK + 'prefLabel', SK + 'altLabel'):
            for o in a.objs(s, p):
                if o[0] == 'L': idx.setdefault(kb.norm(o[1]), s[1])
FIN = BASE + 'vocabulary/domain-finance/'
for w, t in (('revenue', 'revenue'), ('budget', 'budget'), ('prepaid', 'prepayment'), ('prepayment', 'prepayment'), ('cash', 'cash'),
             ('cash equivalent', 'cash-equivalent'), ('receivable', 'receivable'), ('investment', 'investment'),
             ):
    idx[kb.norm(w)] = FIN + t
for w in ('financial', 'fiscal', 'finance'):
    idx[kb.norm(w)] = BASE + 'vocabulary/core-domain/finance'      # the finance business domain (decision 20)
STOP = {'and', 'of', 'the', 'for', 'to', 'in', 'or', 'a', 'an', 'with', 'by', 'on', 'at', 'as', 'per', 'into', 'from', 'vs', 'non', 'sub', 'based', 'between', 'key', 'reached', 'raised', 'facing', 'supporting', 'pass', 'handling'}
HEAD_BEFORE_OF = True
def decompose(label):
    toks = kb.norm(label).split()
    whole = ' '.join(toks)
    if whole in idx: return [idx[whole]], [], idx[whole]
    parts, miss, heads, i = [], [], [], 0
    of_at = toks.index('of') if 'of' in toks else None
    while i < len(toks):
        for j in range(len(toks), i, -1):
            g = ' '.join(toks[i:j])
            if g in idx and (j - i > 1 or toks[i] not in STOP):
                parts.append(idx[g]); heads.append((i, idx[g])); i = j; break
        else:
            if toks[i] not in STOP: miss.append(toks[i])
            i += 1
    head = None
    if heads:
        pre = [t for pos, t in heads if of_at is None or pos < of_at]
        head = (pre or [t for _, t in heads])[-1]
    seen, uniq = set(), []
    for p in parts:
        if p not in seen: seen.add(p); uniq.append(p)
    return uniq, miss, head

rows = []
for n, a in T.items():
    for s in a.concepts():
        lab = a.pref(s)
        parts, miss, head = decompose(lab)
        old = [o[1] for o in a.objs(s, DCT + 'subject')]
        a.set(s, DCT + 'subject', [I(p) for p in parts])
        a.set(s, PRIMARY, [I(head)] if head else [])
        if set(old) != set(parts): a.set(s, DCT + 'modified', [NOW])
        kind = 'primitive' if len(parts) == 1 and not miss and parts[0] == idx.get(kb.norm(lab)) else ('polymorphic' if parts and not miss else ('partial' if parts else 'unlinked'))
        rows.append([n.replace('taxonomy-core-', ''), s[1].rsplit('/', 1)[1], lab, kind, head.replace(BASE + 'vocabulary/', '') if head else '',
                     ' '.join(p.replace(BASE + 'vocabulary/', '') for p in parts), ' '.join(miss)])
    # dcterms:source: the vocabularies the concepts draw on
    srcs = sorted({p[0][1].rsplit('/', 2)[0] + '/' for s in a.concepts() for p in [a.objs(s, DCT + 'subject')] if p} |
                  {o[1].rsplit('/', 1)[0] + '/' for s in a.concepts() for o in a.objs(s, DCT + 'subject')})
    a.set(a.header, DCT + 'source', [I(x) for x in srcs])
    a.set(a.header, DCT + 'modified', [NOW])

with open(OUT / 'concept-links.csv', 'w', newline='') as f:
    w = csv.writer(f); w.writerow(['taxonomy', 'concept', 'label', 'kind', 'primary_term', 'subjects', 'unmatched_words']); w.writerows(rows)
with open(OUT / 'crosswalk-taxonomy.csv', 'w', newline='') as f:
    w = csv.writer(f); w.writerow(['old_iri', 'new_iri', 'note']); w.writerows(cross)
for n, a in T.items():
    a.write(OUT / 'ttl', OUT / 'trig', name=n + '-0.1.0', extra_prefixes={'core': CORE})
c = collections.Counter(r[3] for r in rows)
print('\n'.join(report['outside'])); print(len(rows), 'concepts:', dict(c), '| renamed', len(ren))
print('unmatched words:', collections.Counter(w for r in rows for w in r[6].split()).most_common(40))
