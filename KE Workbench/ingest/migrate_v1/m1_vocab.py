"""Step 1: vocabularies. New core vocabularies, primitives backfill, job terms moved out of requirements,
Verizon-free persona (no role typing), product marketing-stage terms removed."""
import csv, datetime, glob, pathlib, sys, collections
import kb
from kb import I, L, SK, RDF, RDFS, OWL, DCT, XSD, TYPE, CORE, BASE

SRC = pathlib.Path(sys.argv[1])          # folder with ttl/
OUT = pathlib.Path(sys.argv[2])          # folder to write ttl/ trig/
REG = pathlib.Path(sys.argv[3])          # primitives-v1.tsv
NOW = L(datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'), None, XSD + 'dateTime')
TODAY = L(datetime.date.today().isoformat(), None, XSD + 'date')
AUTHOR = L('Jeffrey Wallk')
NOTE = 'Primitive added 2026-10-19 in the Baseline Core v1.0 primitives backfill; definition drafted for review before the term moves to Candidate.'
(OUT / 'ttl').mkdir(parents=True, exist_ok=True); (OUT / 'trig').mkdir(parents=True, exist_ok=True)

A = {p.name[:-10]: kb.Asset(p) for p in sorted((SRC / 'ttl').glob('*-0.1.0.ttl'))}
V = {n: a for n, a in A.items() if n.startswith('vocabulary-')}
log, cross = [], []

def gov(a, s, created=TODAY):
    a.set(s, CORE + 'hasLifecycleStatus', [I(CORE + 'Draft')]); a.set(s, OWL + 'versionInfo', [L('0.1.0')])
    a.set(s, DCT + 'creator', [AUTHOR])
    if not a.objs(s, DCT + 'created'): a.set(s, DCT + 'created', [created])
    a.set(s, DCT + 'modified', [NOW])

# ── 1. new vocabularies ──────────────────────────────────────────────────────
NEW = {
 'decision': ('Core decision vocabulary', 'A controlled vocabulary of the primitives used to classify decisions, decision models and how decisions are made.'),
 'governance': ('Core governance vocabulary', 'A controlled vocabulary of the primitives used to classify governance bodies, activities, controls and records.'),
 'job': ('Core job vocabulary', 'A controlled vocabulary of the primitives of the Jobs model (Jobs To Be Done): jobs, job steps, desired and delivered outcomes and the parties who execute them. It supports the persona model.'),
 'logic': ('Core logic vocabulary', 'A controlled vocabulary of the primitives used to classify the control flow, data flow, orchestration, reasoning and retrieval logic of processes and agents.'),
 'measure': ('Core measure vocabulary', 'A controlled vocabulary of the primitives used to classify measures, indicators, calculations, targets and quality dimensions.'),
 'policy': ('Core policy vocabulary', 'A controlled vocabulary of the primitives used to classify policies, norms, agreements and the legal sources they come from.'),
 'value': ('Core value vocabulary', 'A controlled vocabulary of the primitives used to classify the value an organization creates for clients, stakeholders and society.'),
}
template = V['vocabulary-core-issue']
for d, (title, desc) in NEW.items():
    iri = f'{BASE}vocabulary/core-{d}/'
    a = kb.Asset.__new__(kb.Asset)
    a.path = SRC / 'ttl' / f'vocabulary-core-{d}-0.1.0.ttl'
    a.head = (f'# {title}\n# {iri}  ·  version 0.1.0  ·  Draft\n'
              f'# Generated by migrate_v1.py on {NOW[1]} from primitives-v1.tsv\n'
              f'# Standards: Semantic Governance: Services, Architecture & Integration v1.9 (Draft), Part III\n')
    a.prefixes = dict(template.prefixes); a.prefixes[d + 'voc'] = iri
    a.g, a.order = collections.OrderedDict(), []
    h = I(iri); a.header = h; a.iri = iri
    hp = template.g[template.header]
    a.set(h, TYPE, [I(SK + 'ConceptScheme')])
    for p in (RDFS + 'label', SK + 'prefLabel', DCT + 'title'): a.set(h, p, [L(title, 'en')])
    a.set(h, DCT + 'description', [L(desc, 'en')])
    for p in (DCT + 'subject', DCT + 'publisher', DCT + 'conformsTo', DCT + 'language'): a.set(h, p, hp.get(p, []))
    a.set(h, 'http://www.linkedmodel.org/schema/vaem#namespace', [L(iri, None, XSD + 'anyURI')])
    a.set(h, 'http://purl.org/vocab/vann/preferredNamespacePrefix', [L(d + 'voc')])
    a.set(h, SK + 'changeNote', [L('0.1.0 (2026-10-19): created for Baseline Core v1.0 to hold the primitives of the core ' + d + ' taxonomy.', 'en')])
    a.set(h, OWL + 'versionIRI', [I(iri + '0.1.0/')])
    gov(a, h); a.set(h, DCT + 'contributor', [AUTHOR])
    V[f'vocabulary-core-{d}'] = a
    log.append(f'new vocabulary {iri}')

# ── 2. index existing terms ──────────────────────────────────────────────────
def index():
    idx = {}
    for n, a in V.items():
        for s in a.concepts():
            for p in (SK + 'prefLabel', SK + 'altLabel'):
                for o in a.objs(s, p):
                    if o[0] == 'L': idx.setdefault(kb.norm(o[1]), (n, s))
    return idx

def new_term(vname, label, definition, alts=(), scope=None, note=NOTE):
    a = V[vname]; s = I(a.iri + kb.slug(label))
    if s in a.g:
        return s
    a.set(s, TYPE, [I(SK + 'Concept')])
    a.set(s, RDFS + 'label', [L(label, 'en')]); a.set(s, SK + 'prefLabel', [L(label, 'en')])
    if alts: a.set(s, SK + 'altLabel', [L(x, 'en') for x in alts])
    a.set(s, SK + 'definition', [L(definition, 'en')])
    if scope: a.set(s, SK + 'scopeNote', [L(scope, 'en')])
    a.set(s, SK + 'inScheme', [I(a.iri)]); a.set(s, SK + 'topConceptOf', [I(a.iri)]); a.add(a.header, SK + 'hasTopConcept', s)
    if note: a.set(s, SK + 'editorialNote', [L(note, 'en')])
    gov(a, s)
    return s

# ── 3. job vocabulary: move job, journey, outcome; drop the polymorphic terms ──
req = V['vocabulary-core-requirements']; job = V['vocabulary-core-job']
rq = lambda x: req.iri + x
moves = {'job': 'job', 'journey': 'journey', 'outcome': 'outcome'}
for old, new in moves.items():
    s = I(rq(old)); ns = I(job.iri + new)
    ps = req.g[s]
    new_term('vocabulary-core-job', req.pref(s), req.lit(s, SK + 'definition'),
             [o[1] for o in ps.get(SK + 'altLabel', []) if o[0] == 'L'], note=None)
    job.set(ns, DCT + 'created', ps.get(DCT + 'created', []))
    cross.append((rq(old), job.iri + new, 'moved to the core job vocabulary'))
drop = ['emotional-job', 'functional-job', 'job-step', 'supporting-job', 'job-executor', 'journey-step']
for x in drop: cross.append((rq(x), '', 'polymorphic term: now a concept in the core job taxonomy'))
req.remove([rq(x) for x in list(moves) + drop])
jobp = [('functional', 'A kind of job concerned with the practical task a party is trying to get done.', (), 'Job kinds are functional and emotional; both are evaluated in the context of the job being performed.'),
        ('emotional', 'A kind of job concerned with how a party wants to feel, or to be perceived, while getting a task done.', (), 'A job that involves money is associated with finance; that is a subject association, not a job kind.'),
        ('executor', 'A party that performs a job.', (), 'A job is unique to its executor and gains contextual relevance when combined with the persona executing it.'),
        ('study', 'A structured investigation of the jobs, job steps and desired outcomes of a persona within a defined scope.', (), None),
        ('core', 'The central and most essential part of something.', (), 'Core and related jobs: the job a persona is principally trying to get done, and the jobs that accompany it.')]
for lab, d, al, sc in jobp: new_term('vocabulary-core-job', lab, d, al, sc)

# ── 4. persona: no role typing ───────────────────────────────────────────────
per = V['vocabulary-core-persona']
roles = [s[1] for s in per.concepts() if s[1].endswith(('-engineering-persona', '/persona-role'))]
per.remove(roles); per.set(I(per.iri + 'persona-type'), SK + 'narrower', [])
for r in roles: cross.append((r, '', 'removed: personas are not typed by role (decision 23)'))

# ── 5. product: marketing stages out ─────────────────────────────────────────
prod = V['vocabulary-core-product']
gone = [prod.iri + x for x in ('decline', 'growth', 'introduction', 'maturity', 'product-lifecycle')]
dev = I(prod.iri + 'development')
prod.set(dev, SK + 'broader', [I(prod.iri + 'product')])
prod.remove(gone)
for x in gone: cross.append((x, '', 'removed: products use the asset lifecycle stages (decisions 11, 24)'))

# ── 6. the primitives registry ───────────────────────────────────────────────
idx = index()
reg = [{k: (v or '') for k, v in r.items()} for r in csv.DictReader((l for l in REG.open(encoding='utf-8') if not l.startswith('#')), delimiter='\t')]
added, merged = collections.Counter(), []
for r in reg:
    lab, voc = r['label'].strip(), r['vocabulary'].strip()
    alts = [x.strip() for x in r['alt_labels'].split(';') if x.strip()]
    hit = idx.get(kb.norm(lab))
    if hit:
        n, s = hit; a = V[n]
        for x in alts: a.add(s, SK + 'altLabel', L(x, 'en'))
        if r['scope_note'].strip() and not a.objs(s, SK + 'scopeNote'): a.set(s, SK + 'scopeNote', [L(r['scope_note'].strip(), 'en')])
        if not a.objs(s, SK + 'definition'): a.set(s, SK + 'definition', [L(r['definition'].strip(), 'en')])
        if alts or r['scope_note'].strip(): a.set(s, DCT + 'modified', [NOW])
        merged.append((lab, voc, n.replace('vocabulary-', ''), s[1]))
        continue
    if 'vocabulary-' + voc not in V: raise SystemExit(f'unknown vocabulary {voc} for {lab}')
    new_term('vocabulary-' + voc, lab, r['definition'].strip(), alts, r['scope_note'].strip() or None)
    added[voc] += 1
    idx = index()
# extra alternative labels on existing terms
for vname, local, alts in (('vocabulary-core-party', 'person', ['human']), ('vocabulary-core-lifecycle', 'develop', ['development']), ('vocabulary-core-time', 'time', ['temporal']), ('vocabulary-core-process', 'delivery', ['delivered']), ('vocabulary-core-rules', 'relation', ['related']), ('vocabulary-core-location', 'uniform-resource-locator', ['web address']), ('vocabulary-core-party', 'organization', ['organizational', 'internal'])):
    s = I(V[vname].iri + local)
    if s in V[vname].g:
        for x in alts: V[vname].add(s, SK + 'altLabel', L(x, 'en'))

for n, a in V.items():
    a.write(OUT / 'ttl', OUT / 'trig', name=n + '-0.1.0')
with open(OUT / 'm1-report.txt', 'w') as f:
    f.write('\n'.join(log) + '\n')
    f.write(f'added {sum(added.values())} primitives: ' + ', '.join(f'{k} {v}' for k, v in sorted(added.items())) + '\n')
    f.write(f'{len(merged)} registry rows matched an existing term (alternative labels/scope notes added there):\n')
    for m in merged: f.write('  ' + ' | '.join(m) + '\n')
with open(OUT / 'crosswalk-vocabulary.csv', 'w', newline='') as f:
    w = csv.writer(f); w.writerow(['old_iri', 'new_iri', 'note']); w.writerows(cross)
print(open(OUT / 'm1-report.txt').read()[:4000])
